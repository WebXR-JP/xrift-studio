import {expect,test} from '@playwright/test';
import {mkdirSync} from 'node:fs';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

test('透過画像30点を検索し、背景確認から実PNGの追加と再利用まで進める',async({page})=>{
  await page.setViewportSize({width:1600,height:1000});
  await page.goto('/e2e.html?scenario=ready');
  await page.getByRole('button',{name:/新規プロジェクト/}).click();
  await page.getByRole('button',{name:/ワールドをビジュアルで作る/}).click();
  await page.getByRole('radio',{name:/空のワールド|Blank/}).click();
  await page.getByLabel('プロジェクト名').fill('transparent-texture-isolated-check');
  await page.getByRole('button',{name:'作成して開く'}).click();
  await page.getByRole('button',{name:'アセットストア',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('button',{name:/^透過画像 同梱30点/}).click();
  const catalog=dialog.getByRole('region',{name:'透過画像のアセット一覧'});
  await expect(catalog.locator('[data-catalog-card]')).toHaveCount(30);
  await catalog.getByRole('combobox',{name:'透過画像のカテゴリ'}).selectOption('動物');
  await expect(catalog.locator('[data-catalog-card]')).toHaveCount(6);
  await catalog.getByRole('textbox',{name:'透過画像を検索'}).fill('rabbit');
  await expect(catalog.locator('[data-catalog-card]')).toHaveCount(1);
  await catalog.locator('[data-catalog-card]').click();
  const detail=dialog.getByLabel('選択したアセットの詳細');
  await expect(detail.getByRole('img',{name:'うさぎのプレビュー'})).toBeVisible();
  await expect.poll(()=>detail.getByRole('img').evaluate((image:HTMLImageElement)=>image.complete&&image.naturalWidth===1254)).toBe(true);
  await detail.getByRole('button',{name:'暗い',exact:true}).click();
  await expect(detail.getByRole('button',{name:'暗い',exact:true})).toHaveAttribute('aria-pressed','true');
  mkdirSync('node_modules/.cache/transparent-texture-verification',{recursive:true});
  await dialog.screenshot({path:'node_modules/.cache/transparent-texture-verification/store-desktop.png'});
  await detail.getByRole('button',{name:'プロジェクトに追加',exact:true}).click();
  await expect(detail.getByRole('status')).toContainText('うさぎ');
  await detail.getByRole('button',{name:'プロジェクトに追加',exact:true}).click();
  await expect(detail.getByRole('status')).toContainText('Assetsで選択されています');
  const errors=await page.evaluate(()=>window.__XRIFT_RELEASE_E2E__?.unhandledCommands??[]);
  expect(errors).toEqual([]);
});

test('ブラウザ版でPNGを保存し、実ストレージへの追加と再読み込み後の透過設定を保つ',async({page})=>{
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/editor.html');
  await page.getByRole('button',{name:/新規プロジェクト/}).click();
  await page.getByRole('button',{name:/ワールドを作る/}).click();
  await page.getByRole('textbox',{name:'プロジェクト名'}).fill('transparent-browser-assets');
  await page.getByRole('button',{name:'作成して開く'}).click();
  await page.getByRole('button',{name:'アセットストア',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'アセットストア'});
  await dialog.getByRole('button',{name:/^透過画像 同梱30点/}).click();
  await dialog.getByRole('textbox',{name:'透過画像を検索'}).fill('うさぎ');
  await dialog.locator('[data-catalog-card]').click();
  const downloading=page.waitForEvent('download');
  await dialog.getByRole('link',{name:'PNGを保存',exact:true}).click();
  const download=await downloading;expect(download.suggestedFilename()).toBe('rabbit.png');
  const downloaded=await readFile((await download.path())!);
  const original=await readFile('public/visual-editor/transparent-textures/v1/rabbit.png');
  expect(downloaded.equals(original)).toBe(true);
  const expectedHash=createHash('sha256').update(original).digest('hex');
  await dialog.getByRole('button',{name:'プロジェクトに追加',exact:true}).click();
  await expect(dialog.getByRole('status')).toContainText('Assetsで選択されています');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'編集を始める',exact:true}).click();
  await dialog.screenshot({path:'node_modules/.cache/transparent-texture-verification/store-mobile.png'});
  await page.setViewportSize({width:1440,height:1000});
  await dialog.getByRole('button',{name:'「アセットストア」を閉じる'}).click();
  await expect(page.getByRole('status',{name:'変更は自動保存されています'})).toBeVisible();
  const stored=await page.evaluate(async()=>{
    const source='/src/lib/browser-project-storage.ts';
    const storage=await import(/* @vite-ignore */ source);
    const project=(await storage.listBrowserProjects()).find((p:{name:string})=>p.name==='transparent-browser-assets');
    const files:Map<string,Uint8Array>=await storage.getBrowserProjectFiles(project.path);
    const bytes=[...files].find(([name])=>/transparent-textures\/rabbit-.*\.png$/.test(name))![1];
    const hash=[...new Uint8Array(await crypto.subtle.digest('SHA-256',new Uint8Array(bytes).buffer))].map(b=>b.toString(16).padStart(2,'0')).join('');
    const saved=await storage.readBrowserVisualProject(project.path);
    const assets=JSON.parse(saved.assetManifestJson).assets;
    const material=Object.values(assets).find((asset:any)=>asset.kind==='material'&&asset.attribution?.providerId==='xrift-transparent-textures') as any;
    return {hash,alpha:material.properties.alphaMode,doubleSided:material.properties.doubleSided,license:[...files.keys()].includes('assets/imported/transparent-textures/LICENSE.txt')};
  });
  expect(stored).toEqual({hash:expectedHash,alpha:'BLEND',doubleSided:true,license:true});
  await page.reload();
  await page.getByRole('button',{name:/ワールド ビジュアルエディター transparent-browser-assets/}).click();
  await expect(page.getByRole('button',{name:/Textures 1/})).toBeVisible();
});
