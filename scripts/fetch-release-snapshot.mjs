// Bakes the current latest release into the landing page.
//
// The page asks GitHub for the latest release at runtime, but that request can
// be slow, rate limited, or blocked, and the download button has to say what it
// is about to download before any of that resolves. So the published bundle
// carries a snapshot taken at build time, and the runtime fetch only replaces
// it when it comes back with something newer.
//
// The release workflow is not involved: this reads the public releases API
// after the fact. `.github/workflows/pages.yml` runs it before the preview
// build, and also redeploys the page when a release is published, so the
// snapshot follows releases without touching how they are made.
//
//   node scripts/fetch-release-snapshot.mjs
//
// A failed fetch is not a build failure. The previously committed snapshot
// stays in place and the page still corrects itself at runtime.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUTPUT = fileURLToPath(
  new URL("../src/preview/generated/release-snapshot.ts", import.meta.url),
);
const API = "https://api.github.com/repos/WebXR-JP/xrift-studio/releases/latest";

const HEADER = `// Generated by scripts/fetch-release-snapshot.mjs. Do not edit by hand.
//
// A build-time copy of the latest release, so the download button can name the
// file, its size and its version on first paint. \`useLatestRelease\` replaces
// this with the live release when the GitHub API answers.

import type { LatestReleaseInput } from "../lib/release-download";

export const RELEASE_SNAPSHOT: LatestReleaseInput = `;

async function main() {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "xrift-studio-release-snapshot",
  };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }

  const response = await fetch(API, { headers });
  if (!response.ok) {
    throw new Error(`GitHub API responded ${response.status}`);
  }

  const release = await response.json();
  const snapshot = {
    tag_name: release.tag_name,
    html_url: release.html_url,
    published_at: release.published_at ?? null,
    assets: (release.assets ?? [])
      .map((asset) => ({
        name: asset.name,
        browser_download_url: asset.browser_download_url,
        size: asset.size,
        digest: asset.digest ?? null,
      }))
      .sort((a, b) => a.name.localeCompare(b.name)),
  };

  writeFileSync(
    OUTPUT,
    `${HEADER}${JSON.stringify(snapshot, null, 2)};\n`,
    "utf8",
  );
  console.log(`Release snapshot updated: ${snapshot.tag_name}`);
}

main().catch((error) => {
  console.warn(
    `Release snapshot not updated (${error.message}). Keeping the committed snapshot.`,
  );
});
