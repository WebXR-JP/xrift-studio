import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "src/lib/visual-editor/world-authoring-guide.json");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new Error("Usage: node scripts/generate-authoring-skill.mjs [--check]");
}

const guide = JSON.parse(await readFile(sourcePath, "utf8"));
const text = (value) => typeof value === "string" && value.trim().length > 0;
if (
  guide.version !== 1 ||
  !Array.isArray(guide.core) || !guide.core.length || !guide.core.every(text) ||
  !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(guide.skill?.name ?? "") ||
  guide.skill.name.length > 64 || !text(guide.skill.description) ||
  Object.keys(guide.routes ?? {}).sort().join(",") !== "assets,blender,r3f" ||
  !Object.values(guide.routes).every((route) => text(route.summary) &&
    Array.isArray(route.instructions) && route.instructions.length > 0 && route.instructions.every(text))
) {
  throw new Error("world-authoring-guide.json has an unsupported or incomplete guide.");
}

const code = (value) => "`" + value + "`";
const content = `---
name: ${guide.skill.name}
description: ${JSON.stringify(guide.skill.description)}
---

<!-- Generated by scripts/generate-authoring-skill.mjs. Edit the shared guide, then regenerate. -->

# Create with XRift Studio

Start with ${code("list_projects")} and the current Scene. The connected Studio exposes the current authoring guide through ${code("get_world_authoring_guide")}. Use ${code('topic: "overview"')} for available routes, then read only the route being used: ${Object.keys(guide.routes).map(code).join(", ")}.

${guide.core.map((instruction) => `- ${instruction}`).join("\n\n")}

For retained static source, use ${code("apply_r3f_scene")} to create or revise the owning root. Read that root with ${code("get_entity_components")} and use its complete ${code("r3fAuthoring.source")} before a revision; generic component-code import is not a retained-source update. Tool schemas and returned capabilities define supported operations and limits.

For a whole-place run, resume with ${code("get_world_authoring")} or save the blueprint and criteria with ${code("begin_world_authoring")}. Use the current revision for writes. Capture the saved result from spawn and iso, record each criterion through ${code("review_world_authoring")}, and finish with ${code("complete_world_authoring")}. A small direct edit does not require a whole-world run.

The [shared guide](../../../src/lib/visual-editor/world-authoring-guide.json) supplies the same core to Studio ChatGPT, MCP and this skill. Detailed route instructions are retrieved on demand; do not read every route before starting.
`;

let stale = false;
for (const directory of [".agents/skills", ".claude/skills"]) {
  const destination = path.join(root, directory, guide.skill.name, "SKILL.md");
  if (check) {
    let existing;
    try { existing = await readFile(destination, "utf8"); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (existing !== content) {
      console.error(`Authoring skill needs regeneration: ${path.relative(root, destination)}`);
      stale = true;
    }
  } else {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, content, "utf8");
    console.log(`Generated ${path.relative(root, destination)}`);
  }
}
if (stale) process.exitCode = 1;
else if (check) console.log("Authoring skills match the shared guide.");
