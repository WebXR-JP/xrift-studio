const PACKAGE_IDENTIFIER = "WebXR-JP.XRiftStudio";
const PACKAGE_NAME = "XRift Studio";
const MANIFEST_VERSION = "1.9.0";
const REPOSITORY_URL = "https://github.com/WebXR-JP/xrift-studio";

// Tauri CLI 2.11.4 uses the second part of bundle.identifier when
// bundle.publisher is unset. Keep the WinGet identity equal to Windows ARP.
// https://github.com/tauri-apps/tauri/blob/tauri-cli-v2.11.4/crates/tauri-bundler/src/bundle/windows/nsis/mod.rs
const WINDOWS_PUBLISHER = "xrift";

function validateHttpsUrl(value, label) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`${label} must be an absolute HTTPS URL`);
  }
  if (
    typeof value !== "string" ||
    /[\s\u0000-\u001f\u007f]/u.test(value) ||
    url.protocol !== "https:" ||
    url.username ||
    url.password ||
    url.hash
  ) {
    throw new Error(`${label} must be an absolute HTTPS URL without credentials or fragments`);
  }
}

// JSON-quoted scalars are valid YAML and preserve URLs and numeric-looking hashes.
const yamlString = (value) => JSON.stringify(value);

function manifestHeader(type) {
  return `# Generated by scripts/update-package-managers.mjs. Do not edit by hand.
# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${MANIFEST_VERSION}.schema.json

`;
}

/** Render the three-file WinGet manifest for the published Windows x64 NSIS installer. */
export function renderWingetManifests({ version, installerUrl, sha256, releaseUrl }) {
  if (typeof version !== "string" || !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version)) {
    throw new Error("version must be a stable semantic version without a v prefix");
  }
  if (typeof sha256 !== "string" || !/^[a-f\d]{64}$/i.test(sha256)) {
    throw new Error("sha256 must contain exactly 64 hexadecimal characters");
  }
  validateHttpsUrl(installerUrl, "installerUrl");
  validateHttpsUrl(releaseUrl, "releaseUrl");

  const directory = `packaging/winget/manifests/w/WebXR-JP/XRiftStudio/${version}`;
  const identity = `PackageIdentifier: ${PACKAGE_IDENTIFIER}\nPackageVersion: ${yamlString(version)}\n`;
  const footer = (type) => `ManifestType: ${type}\nManifestVersion: ${MANIFEST_VERSION}\n`;

  // /P is Tauri's passive mode. /R would launch the app after installation;
  // /UPDATE skips missing WebView2 installation, so neither is applied here.
  // The installer itself handles upgrades and downloads WebView2 when needed.
  // https://github.com/tauri-apps/tauri/blob/tauri-cli-v2.11.4/crates/tauri-bundler/src/bundle/windows/nsis/installer.nsi
  const installer = `${manifestHeader("installer")}${identity}InstallerType: nullsoft
Scope: user
InstallModes:
  - interactive
  - silent
  - silentWithProgress
InstallerSwitches:
  Silent: /S
  SilentWithProgress: /P
UpgradeBehavior: install
FileExtensions:
  - xriftstudio
AppsAndFeaturesEntries:
  - DisplayName: ${PACKAGE_NAME}
    Publisher: ${WINDOWS_PUBLISHER}
Installers:
  - Architecture: x64
    InstallerUrl: ${yamlString(installerUrl)}
    InstallerSha256: ${yamlString(sha256.toUpperCase())}
${footer("installer")}`;

  const defaultLocale = `${manifestHeader("defaultLocale")}${identity}PackageLocale: en-US
Publisher: ${WINDOWS_PUBLISHER}
PublisherUrl: ${REPOSITORY_URL}
PublisherSupportUrl: ${REPOSITORY_URL}/issues
Author: xrift-studio contributors
PackageName: ${PACKAGE_NAME}
PackageUrl: https://webxr-jp.github.io/xrift-studio/
License: MIT
ShortDescription: Community-built desktop app for creating XRift worlds and items
Moniker: xrift-studio
Tags:
  - 3d
  - editor
  - vr
  - xrift
ReleaseNotesUrl: ${yamlString(releaseUrl)}
${footer("defaultLocale")}`;

  const versionManifest = `${manifestHeader("version")}${identity}DefaultLocale: en-US
${footer("version")}`;

  return {
    [`${directory}/${PACKAGE_IDENTIFIER}.yaml`]: versionManifest,
    [`${directory}/${PACKAGE_IDENTIFIER}.installer.yaml`]: installer,
    [`${directory}/${PACKAGE_IDENTIFIER}.locale.en-US.yaml`]: defaultLocale,
  };
}
